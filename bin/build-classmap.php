<?php declare(strict_types = 1);

/**
 * Generates classmap.php from Composer's classmap for the directories in the `autoload.classmap`
 * section of composer.json. Runs automatically after Composer generates its autoloader, for example
 * during `composer install` or `composer dump-autoload`.
 */

$root = dirname( __DIR__ );
$composer = json_decode( (string) file_get_contents( $root . '/composer.json' ), true );
$classes = require $root . '/vendor/composer/autoload_classmap.php';
$classmap = [];

foreach ( $classes as $class_name => $file ) {
	foreach ( $composer['autoload']['classmap'] as $dir ) {
		if ( strpos( $file, $root . '/' . trim( $dir, '/' ) . '/' ) === 0 ) {
			$classmap[ $class_name ] = substr( $file, strlen( $root ) );
		}
	}
}

ksort( $classmap );

$output = "<?php\n\n// Generated by bin/build-classmap.php. Do not edit.\n\nreturn [\n";

foreach ( $classmap as $class_name => $file ) {
	$output .= "\t" . var_export( $class_name, true ) . ' => ' . var_export( $file, true ) . ",\n";
}

$output .= "];\n";

file_put_contents( $root . '/classmap.php', $output );

printf( "Wrote %d classes to classmap.php\n", count( $classmap ) );
